"""Aggregate results/*.json into results/summary.json and results/summary.md (per host x system: seeds, ADP mean/sd,
attacks, TP, FP, FP/test day at the system's own threshold). Headline ADP: ProvFusion = random-tie ADP of its vote
score; Velox/ORTHRUS = PIDSMaker ADP (continuous scores)."""
import glob, json, os, re, statistics as st
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
rows = {}
for f in sorted(glob.glob(os.path.join(R, "*_s[0-9].json"))):
    m = re.match(r"(provfusion|velox|orthrus_non_snooped)_(.+)_s(\d)\.json", os.path.basename(f))
    if not m:
        continue
    sysn, host, seed = m.group(1), m.group(2), int(m.group(3)); d = json.load(open(f))
    if sysn == "provfusion":
        op = d["operating_point"]; adp = d["adp_votes"]["adp_random_ties_mean"]
        extra = {"adp_own_gt_first_ties": d["adp_votes"]["adp_gt_first_ties"], "adp_pidsmaker": d["adp_votes"]["adp_pidsmaker"],
                 "adp_worst": d["adp_votes"]["adp_worst_ties"], "adp_vote_then_A123": d["adp_votes_then_A123"]["adp_pidsmaker"]}
        pf = f[:-5] + "_printed.txt"
        if os.path.exists(pf):
            mm = re.search(r"The adp score is: ([0-9.]+)", open(pf).read())
            if mm:
                extra["adp_printed_by_provfusion"] = round(float(mm.group(1)), 4)
    else:
        h = d["headline_last_epoch"]; op = h["operating_point"]; adp = h["adp"]["adp_pidsmaker"]
        extra = {"adp13": h["adp"]["adp13"]}
    rows.setdefault((host, sysn), []).append({"seed": seed, "adp": adp, **{k: op.get(k) for k in ("attacks", "n_attacks", "TP", "FP", "FP_per_test_day", "precision")}, **extra})
out = []
lines = ["| host | system | seeds | ADP mean ± sd (min-max) | ProvFusion-printed ADP per seed | attacks found per seed | TP per seed | FP per seed | FP/test day (mean) |", "|---|---|---|---|---|---|---|---|---|"]
for (host, sysn), rs in sorted(rows.items()):
    rs.sort(key=lambda r: r["seed"]); a = [r["adp"] for r in rs]
    sd = st.stdev(a) if len(a) > 1 else 0.0
    fpd = [r["FP_per_test_day"] for r in rs if r["FP_per_test_day"] is not None]
    out.append({"host": host, "system": sysn, "runs": rs, "adp_mean": round(st.mean(a), 3), "adp_sd": round(sd, 3)})
    lines.append(f"| {host} | {sysn} | {','.join(str(r['seed']) for r in rs)} | {st.mean(a):.2f} ± {sd:.2f} ({min(a):.2f}-{max(a):.2f}) | {', '.join(str(r.get('adp_printed_by_provfusion', '-')) for r in rs)} | "
                 f"{', '.join(f'{r['attacks']}/{r['n_attacks']}' for r in rs)} | {', '.join(str(r['TP']) for r in rs)} | "
                 f"{', '.join(str(r['FP']) for r in rs)} | {st.mean(fpd):.1f} |" if fpd else "")
json.dump(out, open(os.path.join(R, "summary.json"), "w"), indent=1)
hdr = ("# Baseline results (generated by scripts/summarize.py)\n\nHeadline ADP: ProvFusion = expected ADP under random "
       "tie order of its integer vote score (its own label-assisted tie order in summary.json as adp_own_gt_first_ties); "
       "Velox / ORTHRUS (orthrus_non_snooped) = PIDSMaker ADP of the last training epoch. Operating point = each "
       "system's own threshold.\n\n")
open(os.path.join(R, "summary.md"), "w").write(hdr + "\n".join(lines) + "\n")
print(hdr + "\n".join(lines))
