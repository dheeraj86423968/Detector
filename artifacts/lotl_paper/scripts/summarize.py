"""Tables for the LotL counterfactual (PROTOCOL.md). Plain Python (no numpy).
Inputs: OUT/res-<transform>-<set>.json, OUT/rows-<transform>-<set>.json.gz, OUT/inc-<transform>.json (inc13.py, G2),
lab_v10 res13-*.json (reference check), paper_analysis/evidence13.json (the 11 novelty-only attacks).
Usage: python3 summarize.py OUT LAB_V10_RESULTS EVIDENCE13_JSON RESULT_PREFIX"""
import glob, gzip, json, os, sys
from collections import defaultdict

OUT, LAB, EVI, PRE = sys.argv[1:5]
DEV = ["ATLASV2_EDR-h1", "ATLASV2_EDR-h2", "CADETS_E3", "CARBANAKV2_EDR-h1", "CARBANAKV2_EDR-h2", "CARBANAKV2_EDR-h3",
       "CARBANAKV2_EDR-h4", "CARBANAKV2_EDR-h5", "CLEARSCOPE_E3", "FIVEDIRECTIONS_E3", "OPTC_H051", "OPTC_H201", "OPTC_H501",
       "THEIA_E3", "THEIA_E5-theia", "TRACE_E3-trace"]
EXTRA = ["CLEARSCOPE_E5-clearscope"]
V = ["P2", "F3", "L12"]
TR = [t for t in ("none", "lotl", "launder") if glob.glob(f"{OUT}/res-{t}-*.json")]
res = {t: {} for t in TR}
for t in TR:
    for f in glob.glob(f"{OUT}/res-{t}-*.json"):
        r = json.load(open(f)); res[t][r["set"]] = r
inc = {t: (json.load(open(f"{OUT}/inc-{t}.json")) if os.path.exists(f"{OUT}/inc-{t}.json") else {}) for t in TR}
evi = {(o["set"], o["attack"]): o["class"] for o in json.load(open(EVI))["attacks"]}
NOV = {k for k, c in evi.items() if c in ("novelty_gt", "novelty_anchor")}


def classify(rowsf, variant):
    """evidence13.py's rule on one variant's rows, plus learned_only (only learned-layer alerts on ground truth)."""
    r = json.load(gzip.open(rowsf)); rows = r["rows"][variant]
    det = defaultdict(list)
    for x in rows:
        if x["layer"] in ("novelty", "rules"):
            det[x["window_start_ns"]].append(x)
    g, an, corr, learned = defaultdict(set), defaultdict(set), defaultdict(bool), defaultdict(set)
    for x in rows:
        for a in x["attacks"]:
            if x["layer"] in ("novelty", "rules"):
                g[a].add(x["layer"])
            else:
                corr[a] = True; learned[a].add(x["layer"])
                if x["rule"] == "novel_executable_repeat":
                    g[a].add("novelty")
                ctx = r["ctx"].get(x["ctx"], {})
                nb = {e["src"] for e in ctx.get("edges", [])} | {e["dst"] for e in ctx.get("edges", [])}
                an[a] |= {y["layer"] for y in det[x["window_start_ns"]] if y["node_uuid"] in nb}
    out = {}
    for a in r["attacks"]:
        gg, aa = g.get(a, set()), an.get(a, set())
        if "rules" in gg: c = "rule_gt"
        elif "rules" in aa: c = "rule_anchor"
        elif "novelty" in gg: c = "novelty_gt"
        elif "novelty" in aa: c = "novelty_anchor"
        elif corr[a]: c = "learned_only" if learned[a] == {"learned"} else "corroborated_unanchored"
        else: c = "missed"
        out[a] = c
    return out


# ---- reference check
L = ["# LotL counterfactual: results", "", f"Generated by scripts/summarize.py from {os.path.basename(OUT)}/ (transforms: {', '.join(TR)}).", ""]
ref_ok, ref_lines = True, []
for s in DEV:
    r13 = json.load(open(f"{LAB}/res13-{s}.json"))["P2"]
    r = res.get("none", {}).get(s)
    if r is None:
        ref_ok = False; ref_lines.append(f"{s}: reference not scored"); continue
    same = (r["P2"]["attacks"], r["P2"]["TP"], r["P2"]["FP"]) == (r13["attacks"], r13["TP"], r13["FP"])
    ref_ok &= same
    if not same:
        ref_lines.append(f"{s}: res13 {r13['attacks']}/{r13['TP']}/{r13['FP']} vs {r['P2']['attacks']}/{r['P2']['TP']}/{r['P2']['FP']}")
L += ["## Reference check", "", ("P2 on untransformed data reproduces lab_v10 res13 P2 (attacks, TP, FP) on all 16 sets."
      if ref_ok else "**Reference check FAILED**: " + "; ".join(ref_lines)), ""]

# ---- pooled table
pooled = {}
L += ["## Pooled, 16 development sets", "",
      "| data | variant | attacks /30 | TP | FP | FP / host-day | precision | false incidents (G2) / host-day |", "|---|---|---|---|---|---|---|---|"]
for t in TR:
    if not all(s in res[t] for s in DEV):
        L.append(f"| {t} | (incomplete: {len([s for s in DEV if s in res[t]])}/16 sets) | | | | | | |")
    have = [s for s in DEV if s in res[t]]
    days = sum(res[t][s]["days"] for s in have)
    for v in V:
        att = sum(res[t][s][v]["attacks"] for s in have if res[t][s]["gt_nodes"])
        tp = sum(res[t][s][v]["TP"] for s in have); fp = sum(res[t][s][v]["FP"] for s in have)
        fi = sum(inc[t].get(s, {}).get(f"{v}/G2", {}).get("fp_incidents", 0) for s in have) if inc[t] else None
        pooled[(t, v)] = dict(sets=len(have), attacks=att, TP=tp, FP=fp, days=days, fp_day=fp / days, prec=tp / max(1, tp + fp), fp_inc=fi)
        L.append(f"| {t} | {v} | {att} | {tp} | {fp} | {fp / days:.2f} | {tp / max(1, tp + fp):.3f} | "
                 + (f"{fi} ({fi / days:.2f})" if fi is not None else "n/a") + " |")
L.append("")

# ---- per attack
cls = {}
for t in TR:
    for s in DEV + EXTRA:
        f = f"{OUT}/rows-{t}-{s}.json.gz"
        if os.path.exists(f):
            for v in V:
                for a, c in classify(f, v).items():
                    cls[(t, v, s, a)] = c
L += ["## Per attack", "", "Class = evidence13.py rule on that variant's alerts (rule_gt, rule_anchor, novelty_gt, novelty_anchor, "
      "corroborated_unanchored, learned_only, missed). Rules = first alerting layer/rule of the attack's ground-truth nodes "
      "(count of nodes). * = one of the 11 novelty-only attacks of evidence13.", ""]
hdr = "| set | attack | " + " | ".join(f"{t} {v}" for t in TR for v in V) + " |"
L += [hdr, "|" + "---|" * (2 + len(TR) * len(V))]
per_attack = []
for s in DEV + EXTRA:
    if not any(s in res[t] for t in TR):
        continue
    r0 = next(res[t][s] for t in TR if s in res[t])
    if not r0["gt_nodes"]:
        continue
    for a in r0["attacks_all"]:
        rec = {"set": s, "attack": a, "evidence13": evi.get((s, a)), "novelty_only": (s, a) in NOV, "cells": {}}
        cells = []
        for t in TR:
            for v in V:
                r = res[t].get(s)
                if r is None:
                    cells.append("-"); continue
                det = a in r[v]["attacks_found"]
                ru = r[v]["per_attack_gt_rules"].get(a, {})
                c = cls.get((t, v, s, a), "?")
                rec["cells"][f"{t}/{v}"] = {"detected": det, "class": c, "gt_rules": ru}
                cells.append(("**det**" if det else "miss") + f" {c}" + (" (" + ", ".join(f"{k} {n}" for k, n in sorted(ru.items())) + ")" if ru else ""))
        per_attack.append(rec)
        L.append(f"| {s} | {a}{' *' if rec['novelty_only'] else ''} | " + " | ".join(cells) + " |")
L.append("")

# ---- per set TP/FP per host-day
L += ["## Per set: TP / FP per host-day", "", "| set | days | " + " | ".join(f"{t} {v}" for t in TR for v in V) + " |",
      "|" + "---|" * (2 + len(TR) * len(V))]
for s in DEV + EXTRA:
    if not any(s in res[t] for t in TR):
        continue
    d = next(res[t][s]["days"] for t in TR if s in res[t])
    L.append(f"| {s} | {d} | " + " | ".join(
        (f"{res[t][s][v]['TP'] / d:.1f} / {res[t][s][v]['FP'] / d:.1f}" if s in res[t] else "-") for t in TR for v in V) + " |")
L.append("")

# ---- highlights
def det(t, v, s, a):
    r = res.get(t, {}).get(s)
    return r is not None and a in r[v]["attacks_found"]


L += ["## Highlights", ""]
if "lotl" in TR:
    nov = [p for p in per_attack if p["novelty_only"]]
    L.append(f"Novelty-only attacks (evidence13, 11): detected under LotL by P2 {sum(det('lotl', 'P2', p['set'], p['attack']) for p in nov)}, "
             f"F3 {sum(det('lotl', 'F3', p['set'], p['attack']) for p in nov)}, L12 {sum(det('lotl', 'L12', p['set'], p['attack']) for p in nov)}.")
    for p in nov:
        L.append(f"- {p['set']} {p['attack']}: " + "; ".join(f"{v} {p['cells'].get('lotl/' + v, {}).get('class', '-')}" for v in V))
    L.append("")
    dev_att = [p for p in per_attack if p["set"] in DEV]
    for v in V:
        lost = [f"{p['set']} {p['attack']}" for p in dev_att if det("none", v, p["set"], p["attack"]) and not det("lotl", v, p["set"], p["attack"])]
        gained = [f"{p['set']} {p['attack']}" for p in dev_att if not det("none", v, p["set"], p["attack"]) and det("lotl", v, p["set"], p["attack"])]
        L.append(f"{v}: lost under LotL {len(lost)} {lost}; gained {len(gained)} {gained}")
    ruled = [p for p in dev_att if p["cells"].get("none/P2", {}).get("class") in ("rule_gt", "rule_anchor")]
    L.append("")
    L.append(f"Rule-detected under P2 before LotL ({len(ruled)}): " + "; ".join(
        f"{p['set']} {p['attack']} -> {p['cells'].get('lotl/P2', {}).get('class')}" for p in ruled))
    notrule = [p for p in dev_att if p["cells"].get("none/P2", {}).get("class") not in ("rule_gt", "rule_anchor")
               and p["cells"].get("lotl/P2", {}).get("class") in ("rule_gt", "rule_anchor")]
    L.append(f"Not rule-detected before, rule-detected after: {[p['set'] + ' ' + p['attack'] for p in notrule]}")
    rec_ = [f"{p['set']} {p['attack']}" for p in dev_att if det("lotl", "F3", p["set"], p["attack"]) and not det("lotl", "P2", p["set"], p["attack"])]
    if ("lotl", "F3") in pooled:
        a, b = pooled[("lotl", "F3")], pooled[("lotl", "P2")]
        L.append(f"F3 recovers {len(rec_)} attacks over P2 under LotL {rec_}; FP {b['FP']} -> {a['FP']} (+{a['FP'] - b['FP']}, "
                 f"{b['fp_day']:.2f} -> {a['fp_day']:.2f} per host-day)" + (f", false incidents {b['fp_inc']} -> {a['fp_inc']}" if a["fp_inc"] is not None else ""))
    L.append("")
    L += ["## Transform per set", "", "| set | renamed process nodes | of them ground truth | targets (kind -> replacement) |", "|---|---|---|---|"]
    for s in DEV + EXTRA:
        r = res["lotl"].get(s)
        if r is None:
            continue
        lt = r["transform"].get("lotl", {})
        tg = "; ".join(f"{x['key'][-40:]} ({x['kind']}{', fallback' if x['fallback_to_process'] else ''}) -> {(x['replacement'] or '')[-45:]}" for x in lt.get("targets", [])[:6])
        more = len(lt.get("targets", [])) - 6
        L.append(f"| {s} | {lt.get('renamed_nodes')} | {lt.get('renamed_gt')} | {tg}{f' (+{more} more)' if more > 0 else ''} |")
open(PRE + ".md", "w").write("\n".join(L) + "\n")
json.dump({"reference_ok": ref_ok, "pooled": {f"{t}/{v}": x for (t, v), x in pooled.items()}, "per_attack": per_attack}, open(PRE + ".json", "w"), indent=1)
print("\n".join(L))
