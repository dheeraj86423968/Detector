#!/usr/bin/env bash
# Publicly trusted HTTPS for the console (Let's Encrypt, HTTP-01 through the gateway's port 80).
#   ./deploy/acme.sh issue     obtain the certificate for PDP_PUBLIC_HOSTNAME and enable the public server
#   ./deploy/acme.sh renew     renew when due (run daily by pdp-acme-renew.timer) and reload the gateway
# The public hostname gets the Let's Encrypt certificate (SNI); localhost, the internal names and the agent port keep
# the internal CA's certificate, which agents and the desktop app pin. Browsers that open the console by IP address
# are redirected to the public hostname.
# Needs: PDP_PUBLIC_HOSTNAME in deploy/.env (a DNS name resolving to this host; e.g. <a-b-c-d>.sslip.io for a bare
# IP), inbound TCP 80 reachable from the internet. Optional PDP_ACME_EMAIL (expiry notices), PDP_ACME_STAGING=1.
set -euo pipefail
cd "$(dirname "$0")/.."
set -a; . deploy/.env; set +a
HOST="${PDP_PUBLIC_HOSTNAME:?set PDP_PUBLIC_HOSTNAME in deploy/.env}"
IMG=certbot/certbot:v3.0.1
CB=(docker run --rm -v pdp_pdp_acme:/etc/letsencrypt -v pdp_pdp_acme_web:/acme "$IMG")
ACCT=(--register-unsafely-without-email); [ -n "${PDP_ACME_EMAIL:-}" ] && ACCT=(--email "$PDP_ACME_EMAIL")
STAGE=(); [ "${PDP_ACME_STAGING:-0}" = 1 ] && STAGE=(--test-cert)

write_conf() {
  cat > deploy/nginx/public/console-public.conf <<CONF
# generated by deploy/acme.sh for ${HOST}
server {
    listen 443 ssl;
    http2 on;
    server_name ${HOST};
    ssl_certificate     /etc/letsencrypt/live/${HOST}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${HOST}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:pub:10m;
    include /etc/nginx/snippets/console.conf;
}
CONF
  cat > deploy/nginx/public/ip.redirect <<CONF
# generated by deploy/acme.sh: browsers that open the console by IP address go to the trusted hostname
if (\$host ~ "^[0-9.]+\$") { return 301 https://${HOST}\$request_uri; }
CONF
}

reload() { docker exec pdp-gateway-1 nginx -t -q && docker exec pdp-gateway-1 nginx -s reload; }

case "${1:-issue}" in
  issue)
    "${CB[@]}" certonly --webroot -w /acme -d "$HOST" --agree-tos --non-interactive --keep-until-expiring \
        "${ACCT[@]}" "${STAGE[@]}" --key-type ecdsa
    write_conf; reload
    echo "console: https://${HOST}/" ;;
  renew)
    "${CB[@]}" renew --webroot -w /acme --quiet
    [ -f deploy/nginx/public/console-public.conf ] || write_conf
    reload ;;
  *) echo "usage: $0 issue|renew" >&2; exit 2 ;;
esac
