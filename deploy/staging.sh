#!/bin/bash
# Staging: a second, independent copy of the server stack on this host for release checks, restore tests and load
# tests. Own compose project (pdp-staging), volumes, network, secrets and ports; CPU training; no public hostname
# (self-signed console certificate), open sign-up, a known first admin password (deploy/staging.env, mode 600).
#
#   deploy/staging.sh up        build nothing, start/refresh staging with the current local images
#   deploy/staging.sh status    containers and the console / agent URLs
#   deploy/staging.sh down      stop (data kept)        deploy/staging.sh destroy   stop and delete all its data
#   deploy/staging.sh env       print the settings tests need (ports, admin password, network)
set -euo pipefail
cd "$(dirname "$0")"
ENV=staging.env
if [ ! -f "$ENV" ]; then
  umask 077
  cat > "$ENV" <<EOV
# staging stack settings (generated by deploy/staging.sh)
PDP_DB_PASSWORD=$(openssl rand -hex 24)
PDP_INITIAL_ADMIN_PASSWORD=$(openssl rand -hex 12)
PDP_KMS=file
PDP_HTTP_PORT=8080
PDP_CONSOLE_PORT=9445
PDP_AGENT_PORT=9446
PDP_REGISTRY_PUSH_PORT=5001
PDP_PUBLIC_HOSTNAME=
PDP_NGINX_PUBLIC=./nginx/public-staging
PDP_SIGNUP=open
PDP_SIGNUPS_PER_HOUR=1000
PDP_ORG_MAX_ENDPOINTS=200
PDP_API_REPLICAS=2
PDP_TRAIN_DEVICE=cpu
PDP_NOTIFY_ALLOW_PRIVATE=0
PDP_INTERNAL_ORG_NAME=Staging
EOV
  echo "generated $ENV"
fi
mkdir -p nginx/public-staging
DC="docker compose -p pdp-staging --env-file $ENV -f docker-compose.yml"
case "${1:-status}" in
  up)
    $DC up -d platform-db telemetry-db
    $DC up -d api worker-ingest worker-train gateway registry notifier
    for i in $(seq 1 60); do
      $DC exec -T api python -c "import urllib.request; urllib.request.urlopen('http://localhost:8000/healthz', timeout=3)" >/dev/null 2>&1 && break
      sleep 2
    done
    "$0" status ;;
  status)
    $DC ps --format '{{.Name}} {{.Status}}'
    set -a; . "./$ENV"; set +a
    echo "console https://<host>:$PDP_CONSOLE_PORT  agent port $PDP_AGENT_PORT  network pdp-staging_edge (gateway host name: gateway)" ;;
  env)
    grep -E '^(PDP_CONSOLE_PORT|PDP_AGENT_PORT|PDP_INITIAL_ADMIN_PASSWORD)=' "$ENV"; echo "NETWORK=pdp-staging_edge" ;;
  down) $DC down ;;
  destroy) $DC down -v ;;
  *) echo "usage: $0 up|status|down|destroy|env" >&2; exit 2 ;;
esac
