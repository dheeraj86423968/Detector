#!/bin/bash
# Staging: a second, independent copy of the server stack on this host for release checks, restore tests and load
# tests. Own compose project (pdp-staging), volumes, network, secrets and ports; CPU training; no public hostname
# (self-signed console certificate), open sign-up, a known first admin password (deploy/staging.env, mode 600).
# Its ports listen on 127.0.0.1 only: from elsewhere use an SSH tunnel (ssh -L 9445:127.0.0.1:9445 this-host).
#
#   deploy/staging.sh up        build nothing, start/refresh staging with the current local images
#   deploy/staging.sh status    containers and the console / agent URLs
#   deploy/staging.sh down      stop (data kept)        deploy/staging.sh destroy   stop and delete all its data
#   deploy/staging.sh env       print the settings tests need (ports, admin password, network)
set -euo pipefail
SELF=$(readlink -f "$0")
cd "$(dirname "$SELF")"
ENV=staging.env
if [ ! -f "$ENV" ]; then
  umask 077
  cat > "$ENV" <<EOV
# staging stack settings (generated by deploy/staging.sh)
PDP_DB_PASSWORD=$(openssl rand -hex 24)
PDP_INITIAL_ADMIN_PASSWORD=$(openssl rand -hex 12)
PDP_KMS=file
PDP_HTTP_PORT=8080
PDP_CONSOLE_PORT=9445
PDP_AGENT_PORT=9446
PDP_REGISTRY_PUSH_PORT=5001
PDP_REGISTRY_HTPASSWD=./nginx/registry-push-staging.htpasswd
PDP_REGISTRY_PUSH_USER=publisher
PDP_REGISTRY_PUSH_PASSWORD=$(openssl rand -hex 24)
PDP_PUBLIC_HOSTNAME=
PDP_NGINX_PUBLIC=./nginx/public-staging
PDP_SIGNUP=open
PDP_SIGNUPS_PER_HOUR=1000
PDP_ORG_MAX_ENDPOINTS=200
PDP_API_REPLICAS=2
PDP_TRAIN_DEVICE=cpu
PDP_NOTIFY_ALLOW_PRIVATE=0
PDP_INTERNAL_ORG_NAME=Staging
PDP_CONSOLE_DIST=../console/dist-next
PDP_HTTPS_PROXY=http://egress:3128
PDP_BIND=127.0.0.1:
EOV
  echo "generated $ENV"
fi
mkdir -p nginx/public-staging
# registry push credentials for the gateway's loopback push listener (same scheme as bringup.sh)
grep -q '^PDP_REGISTRY_PUSH_PASSWORD=' "$ENV" || { umask 077; printf 'PDP_REGISTRY_HTPASSWD=./nginx/registry-push-staging.htpasswd\nPDP_REGISTRY_PUSH_USER=publisher\nPDP_REGISTRY_PUSH_PASSWORD=%s\n' "$(openssl rand -hex 24)" >> "$ENV"; }
( set -a; . "./$ENV"; set +a; umask 077
  printf '%s:%s\n' "$PDP_REGISTRY_PUSH_USER" "$(openssl passwd -apr1 "$PDP_REGISTRY_PUSH_PASSWORD")" > "${PDP_REGISTRY_HTPASSWD:-./nginx/registry-push-staging.htpasswd}" )
# staging serves the console build under test (console: npx vite build --outDir dist-next); production serves
# console/dist, updated only when production's API is rolled (docs/OPERATIONS.md), so it never runs ahead of its API
grep -q '^PDP_CONSOLE_DIST=' "$ENV" || echo 'PDP_CONSOLE_DIST=../console/dist-next' >> "$ENV"
grep -q '^PDP_BIND=' "$ENV" || echo 'PDP_BIND=127.0.0.1:' >> "$ENV"     # open sign-up + known admin: never public
grep -q '^PDP_HTTPS_PROXY=' "$ENV" || echo 'PDP_HTTPS_PROXY=http://egress:3128' >> "$ENV"     # SSO + domain proof via egress
grep -q '^PDP_TELEMETRY_SHARED_BUFFERS=' "$ENV" || echo 'PDP_TELEMETRY_SHARED_BUFFERS=1GB' >> "$ENV"   # staging holds little data; RAM is shared with production
[ -f ../console/dist-next/index.html ] || { mkdir -p ../console/dist-next && cp -a ../console/dist/. ../console/dist-next/; }
DC="docker compose -p pdp-staging --env-file $ENV -f docker-compose.yml"
case "${1:-status}" in
  up)
    $DC up -d platform-db telemetry-db
    $DC --profile sso up -d egress
    $DC up -d api worker-ingest worker-train gateway registry notifier
    for i in $(seq 1 60); do
      $DC exec -T api python -c "import urllib.request; urllib.request.urlopen('http://localhost:8000/healthz', timeout=3)" >/dev/null 2>&1 && break
      sleep 2
    done
    "$SELF" status ;;
  status)
    $DC ps --format '{{.Name}} {{.Status}}'
    set -a; . "./$ENV"; set +a
    echo "console https://<host>:$PDP_CONSOLE_PORT  agent port $PDP_AGENT_PORT  network pdp-staging_edge (gateway host name: gateway)" ;;
  env)
    grep -E '^(PDP_CONSOLE_PORT|PDP_AGENT_PORT|PDP_INITIAL_ADMIN_PASSWORD)=' "$ENV"; echo "NETWORK=pdp-staging_edge" ;;
  down) $DC down ;;
  destroy) $DC down -v ;;
  *) echo "usage: $0 up|status|down|destroy|env" >&2; exit 2 ;;
esac
